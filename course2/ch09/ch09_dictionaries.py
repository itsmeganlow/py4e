# INSERT VALUES INTO DICTIONARY USING A KEY
cabinet = dict()
cabinet['summer'] = 12 # [SUMMER] IS THE KEY > 12 IS THE VALUE
cabinet['fall'] = 3
cabinet['spring'] = 75
print(cabinet)

print(cabinet['fall'])

cabinet['fall'] = cabinet['fall'] + 2
print(cabinet)

